"""Offline evaluation of AtlasTrace on all 1,190 labelled XQuAD questions.

Retrieval (index only)
    Recall@1 / Recall@5 / MRR@10 of the gold passage, for English questions,
    Vietnamese questions, and Vietnamese questions against an English-only index
    (the baseline the bilingual index is meant to beat).

End to end (Demo pipeline, deterministic)
    Gold passage cited first, gold answer contained in the extracted sentence,
    share of runs that triggered the corrective loop, latency.

Usage:
    python scripts/evaluate.py                 # print the report
    python scripts/evaluate.py --write         # also write eval/report.json and eval/REPORT.md
    python scripts/evaluate.py --limit 200     # quick run on the first 200 questions
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from atlastrace.corpus import load_questions  # noqa: E402
from atlastrace.graph import run_state  # noqa: E402
from atlastrace.retrieval import get_index  # noqa: E402
from atlastrace.text import deaccent  # noqa: E402


def contains(text: str, answers: tuple[str, ...]) -> bool:
    folded = deaccent(text.lower())
    return any(deaccent(answer.lower()) in folded for answer in answers)


def retrieval_metrics(questions, lang: str, langs: tuple[str, ...]) -> dict[str, float]:
    index = get_index(langs)
    r1 = r5 = mrr = 0.0
    for question in questions:
        ids = [hit.passage.id for hit in index.search([question.question(lang)], limit=10)]
        if ids and ids[0] == question.passage_id:
            r1 += 1
        if question.passage_id in ids[:5]:
            r5 += 1
        if question.passage_id in ids:
            mrr += 1 / (ids.index(question.passage_id) + 1)
    n = len(questions)
    return {"recall@1": r1 / n, "recall@5": r5 / n, "mrr@10": mrr / n}


def pipeline_metrics(questions, lang: str) -> dict[str, float]:
    cited_gold = answer_hit = corrective = not_found = 0
    latencies = []
    for question in questions:
        started = time.perf_counter()
        state = run_state(question.question(lang), locale=lang, mode="demo")
        latencies.append((time.perf_counter() - started) * 1000)
        accepted = state["accepted_ids"]
        cited_gold += bool(accepted) and accepted[0] == question.passage_id
        answer_hit += contains(state["extracted_sentence"], question.answers(lang))
        corrective += state["round"] > 1
        not_found += not state.get("answerable", True)
    n = len(questions)
    return {
        "gold_passage_cited_first": cited_gold / n,
        "answer_in_extracted_sentence": answer_hit / n,
        "corrective_loop_rate": corrective / n,
        "not_found_rate": not_found / n,
        "latency_ms_p50": statistics.median(latencies),
        "latency_ms_p95": sorted(latencies)[int(0.95 * (n - 1))],
    }


def to_markdown(report: dict) -> str:
    pct = lambda value: f"{value * 100:.1f}%"  # noqa: E731
    r, p = report["retrieval"], report["pipeline"]
    lines = [
        "# AtlasTrace evaluation report",
        "",
        f"Dataset: XQuAD (EN + VI), {report['n_questions']} labelled questions over {report['n_passages']} passages. Generated by `python scripts/evaluate.py --write`.",
        "",
        "## Retrieval",
        "",
        "| Setting | Recall@1 | Recall@5 | MRR@10 |",
        "| --- | --- | --- | --- |",
    ]
    for name, label in (
        ("en", "English question → bilingual index"),
        ("vi", "Vietnamese question → bilingual index"),
        ("vi_en_only", "Vietnamese question → English-only index (baseline)"),
    ):
        m = r[name]
        lines.append(f"| {label} | {pct(m['recall@1'])} | {pct(m['recall@5'])} | {m['mrr@10']:.3f} |")
    lines += [
        "",
        "## End-to-end pipeline (Demo mode)",
        "",
        "| Language | Gold passage cited first | Answer in extracted sentence | Corrective loop triggered | Flagged not found | p50 latency | p95 latency |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for lang, label in (("en", "English"), ("vi", "Vietnamese")):
        m = p[lang]
        lines.append(
            f"| {label} | {pct(m['gold_passage_cited_first'])} | {pct(m['answer_in_extracted_sentence'])} | {pct(m['corrective_loop_rate'])} | {pct(m['not_found_rate'])} | {m['latency_ms_p50']:.1f} ms | {m['latency_ms_p95']:.1f} ms |"
        )
    lines += [
        "",
        "Notes",
        "",
        "- *Answer in extracted sentence* checks whether the gold answer span appears in the sentence the deterministic synthesizer picked. It is a sentence-level metric, not exact-match span extraction.",
        "- All numbers come from the deterministic pipeline, so they are reproducible run to run. Latency depends on the machine.",
    ]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--limit", type=int, default=None)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()

    questions = load_questions()[: args.limit] if args.limit else load_questions()
    report = {
        "n_questions": len(questions),
        "n_passages": len(get_index().docs) // 2,
        "retrieval": {
            "en": retrieval_metrics(questions, "en", ("en", "vi")),
            "vi": retrieval_metrics(questions, "vi", ("en", "vi")),
            "vi_en_only": retrieval_metrics(questions, "vi", ("en",)),
        },
        "pipeline": {"en": pipeline_metrics(questions, "en"), "vi": pipeline_metrics(questions, "vi")},
    }
    markdown = to_markdown(report)
    print(markdown)

    if args.write:
        out = ROOT / "eval"
        out.mkdir(exist_ok=True)
        (out / "report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        (out / "REPORT.md").write_text(markdown, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
